export function evaluateAtmosphericSafety(readings: {
  o2: number;
  lel: number;
  h2s: number;
  co: number;
}) {
  const o2Ok = readings.o2 >= 19.5 && readings.o2 <= 23.5;
  const lelOk = readings.lel === 0;
  const h2sOk = readings.h2s < 10;
  const coOk = readings.co < 25;
  const allSafe = o2Ok && lelOk && h2sOk && coOk;

  return {
    o2Ok,
    lelOk,
    h2sOk,
    coOk,
    allSafe,
    statusLabel: allSafe
      ? 'APTO PARA INGRESO (API 2015)'
      : 'FUERA DE RANGO CRÍTICO — NO INGRESAR',
  };
}
